void PhonoEngine::ComputeDensity(int begin, int end) noexcept {
    if (!ready_) {
        return;
    }
    if (begin < 0) begin = 0;
    if (end > size_) end = size_;

    const double* __restrict u = psi_real_.data();
    const double* __restrict v = psi_imag_.data();
    double* __restrict d = density_.data();
    for (int i = begin; i < end; ++i) {
        d[i] = u[i] * u[i] + v[i] * v[i];
    }
}

double PhonoEngine::Norm() const noexcept {
    if (!ready_) {
        return 0.0;
    }
    const double* __restrict u = psi_real_.data();
    const double* __restrict v = psi_imag_.data();

    // Four partial sums: floating-point addition is not associative, so
    // this both shortens the dependency chain for the pipeline and keeps
    // the rounding error growing like sqrt(N/4) instead of N.
    double s0 = 0.0, s1 = 0.0, s2 = 0.0, s3 = 0.0;
    int i = 0;
    for (; i + 3 < size_; i += 4) {
        s0 += u[i] * u[i] + v[i] * v[i];
        s1 += u[i + 1] * u[i + 1] + v[i + 1] * v[i + 1];
        s2 += u[i + 2] * u[i + 2] + v[i + 2] * v[i + 2];
        s3 += u[i + 3] * u[i + 3] + v[i + 3] * v[i + 3];
    }
    for (; i < size_; ++i) {
        s0 += u[i] * u[i] + v[i] * v[i];
    }
    return ((s0 + s1) + (s2 + s3)) * CellVolume();
}

void PhonoEngine::Normalize() noexcept {
    if (!ready_) {
        return;
    }
    const double norm = Norm();
    if (!(norm > 0.0)) {
        return;
    }
    const double scale = 1.0 / std::sqrt(norm);
    double* __restrict u = psi_real_.data();
    double* __restrict v = psi_imag_.data();
    for (int i = 0; i < size_; ++i) {
        u[i] *= scale;
        v[i] *= scale;
    }
}

void PhonoEngine::SetGaussianPacket(double x0, double y0, double z0,
                                    double sx, double sy, double sz,
                                    double kx, double ky, double kz) noexcept {
    if (!ready_) {
        return;
    }
    if (!(sx > 0.0) || !(sy > 0.0) || !(sz > 0.0)) {
        return;
    }

    const double inv_2sx2 = 1.0 / (2.0 * sx * sx);
    const double inv_2sy2 = 1.0 / (2.0 * sy * sy);
    const double inv_2sz2 = 1.0 / (2.0 * sz * sz);

    double* __restrict u = psi_real_.data();
    double* __restrict v = psi_imag_.data();

    for (int z = 0; z < depth_; ++z) {
        // Grid point i sits at (i+1)*h: the Dirichlet walls occupy the
        // ghost slots at index -1 and index n.
        const double zc = (static_cast<double>(z) + 1.0) * dz_;
        const double dzr = zc - z0;
        const double gz = dzr * dzr * inv_2sz2;
        for (int y = 0; y < height_; ++y) {
            const double yc = (static_cast<double>(y) + 1.0) * dy_;
            const double dyr = yc - y0;
            const double gy = dyr * dyr * inv_2sy2;
            const std::size_t row =
                (static_cast<std::size_t>(z) * height_ + y) * width_;
            for (int x = 0; x < width_; ++x) {
                const double xc = (static_cast<double>(x) + 1.0) * dx_;
                const double dxr = xc - x0;
                const double gx = dxr * dxr * inv_2sx2;

                const double envelope = std::exp(-(gx + gy + gz));
                const double phase = kx * xc + ky * yc + kz * zc;
                u[row + x] = envelope * std::cos(phase);
                v[row + x] = envelope * std::sin(phase);
            }
        }
    }
    Normalize();
}

