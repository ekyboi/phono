void PhonoEngine::BuildFactors(TridiagFactors& f, int n, double h,
                               double tau) noexcept {
    // r = tau*hbar / (4 m h^2); see derivation section 4.
    const double r = tau * hbar_ / (4.0 * mass_ * h * h);
    f.r = r;

    // a = c = (0, -r); b = (1, 2r).
    //
    // Row 0: w_0 = 1/b. The reciprocal of (br, bi) is
    // (br, -bi)/(br^2+bi^2).
    {
        const double br = 1.0;
        const double bi = 2.0 * r;
        const double inv = 1.0 / (br * br + bi * bi);
        const double wr = br * inv;
        const double wi = -bi * inv;
        f.w_re[0] = wr;
        f.w_im[0] = wi;
        // cp_0 = c*w_0 = (0,-r)*(wr,wi) = (r*wi, -r*wr).
        f.cp_re[0] = r * wi;
        f.cp_im[0] = -r * wr;
    }

    for (int j = 1; j < n; ++j) {
        // denom = b - a*cp_{j-1}. With a = (0,-r):
        //   a*cp = (0,-r)*(cr,ci) = (r*ci, -r*cr)
        const double cr = f.cp_re[j - 1];
        const double ci = f.cp_im[j - 1];
        const double dr = 1.0 - r * ci;
        const double di = 2.0 * r + r * cr;

        const double inv = 1.0 / (dr * dr + di * di);
        const double wr = dr * inv;
        const double wi = -di * inv;
        f.w_re[j] = wr;
        f.w_im[j] = wi;
        f.cp_re[j] = r * wi;
        f.cp_im[j] = -r * wr;
    }
}

void PhonoEngine::MarkPotentialDirty() noexcept { potential_dirty_ = true; }

void PhonoEngine::PrepareStep(double dt) noexcept {
    if (!ready_) {
        return;
    }
    const bool dt_changed = (dt != prepared_dt_);
    if (!dt_changed && !potential_dirty_) {
        return;
    }

    if (dt_changed) {
        // The Strang composition applies x and y with tau = dt/2 (twice
        // each) and z with tau = dt (once).
        BuildFactors(fx_, width_, dx_, 0.5 * dt);
        BuildFactors(fy_, height_, dy_, 0.5 * dt);
        BuildFactors(fz_, depth_, dz_, dt);
        prepared_dt_ = dt;
    }

    // Diagonal half-step phase: Psi <- exp(-i V dt/(2 hbar)) Psi. Static V
    // and fixed dt make this constant in time, so the transcendentals are
    // paid once here rather than Size() times per step.
    const double scale = -0.5 * dt / hbar_;
    for (int i = 0; i < size_; ++i) {
        const double theta = potential_[i] * scale;
        phase_cos_[i] = std::cos(theta);
        phase_sin_[i] = std::sin(theta);
    }
    potential_dirty_ = false;
}

// ---------------------------------------------------------------------
// Phase 1/7: the diagonal (potential) half-step
// ---------------------------------------------------------------------

void PhonoEngine::ApplyPotentialHalfStep(int begin, int end) noexcept {
    if (!ready_) {
        return;
    }
    if (begin < 0) begin = 0;
    if (end > size_) end = size_;

    double* __restrict u = psi_real_.data();
    double* __restrict v = psi_imag_.data();
    const double* __restrict c = phase_cos_.data();
    const double* __restrict s = phase_sin_.data();

    // (c + i s)(u + i v) = (uc - vs) + i(us + vc): a plane rotation of the
    // (Re, Im) pair by the tabulated angle. Pointwise, no dependencies --
    // this is the most trivially vectorisable loop in the engine.
    for (int i = begin; i < end; ++i) {
        const double ur = u[i];
        const double vr = v[i];
        u[i] = ur * c[i] - vr * s[i];
        v[i] = ur * s[i] + vr * c[i];
    }
}

// ---------------------------------------------------------------------
// Phase 2/6: Cayley solve along x
// ---------------------------------------------------------------------
//
// x is the unit-stride axis, so a line is contiguous. The Thomas
// recurrence is inherently serial along the line, and vectorising across
// lines here would mean gathering at stride Width -- so this variant runs
// one line at a time and takes its parallelism from the shard split
// instead, which is the right trade when the line itself is contiguous
// and prefetch-friendly.

void PhonoEngine::SweepX(int worker, int begin, int end) noexcept {
    if (!ready_) {
        return;
    }
    const int lines = XLineCount();
    if (begin < 0) begin = 0;
    if (end > lines) end = lines;

    const int n = width_;
    if (n <= 0) {
        return;
    }

    double* __restrict u = psi_real_.data();
    double* __restrict v = psi_imag_.data();
    const double r = fx_.r;
    const double* __restrict cp_re = fx_.cp_re.data();
    const double* __restrict cp_im = fx_.cp_im.data();
    const double* __restrict w_re = fx_.w_re.data();
    const double* __restrict w_im = fx_.w_im.data();

    double* __restrict dp_re = WorkerScratch(worker);
    double* __restrict dp_im = dp_re + static_cast<std::size_t>(n);

    for (int line = begin; line < end; ++line) {
        const int z = line / height_;
        const int y = line - z * height_;
        const std::size_t base =
            (static_cast<std::size_t>(z) * height_ + y) * width_;

        // ---- forward elimination, fused with RHS construction --------
        // dp_0 = d_0 * w_0
        {
            const double u0 = u[base];
            const double v0 = v[base];
            const double up = (n > 1) ? u[base + 1] : 0.0;
            const double vp = (n > 1) ? v[base + 1] : 0.0;
            const double lap_u = -2.0 * u0 + up;   // ghost wall at j = -1
            const double lap_v = -2.0 * v0 + vp;
            const double d_re = u0 - r * lap_v;
            const double d_im = v0 + r * lap_u;
            dp_re[0] = d_re * w_re[0] - d_im * w_im[0];
            dp_im[0] = d_re * w_im[0] + d_im * w_re[0];
        }

        for (int j = 1; j < n; ++j) {
            const std::size_t idx = base + j;
            const double u0 = u[idx];
            const double v0 = v[idx];
            const double um = u[idx - 1];
            const double vm = v[idx - 1];
            const double up = (j + 1 < n) ? u[idx + 1] : 0.0;
            const double vp = (j + 1 < n) ? v[idx + 1] : 0.0;
            const double lap_u = um - 2.0 * u0 + up;
            const double lap_v = vm - 2.0 * v0 + vp;
            const double d_re = u0 - r * lap_v;
            const double d_im = v0 + r * lap_u;

            // t = d_j - a*dp_{j-1}, with a = (0,-r):
            //   a*dp = (r*dp_im, -r*dp_re)
            const double t_re = d_re - r * dp_im[j - 1];
            const double t_im = d_im + r * dp_re[j - 1];
            // dp_j = t * w_j
            dp_re[j] = t_re * w_re[j] - t_im * w_im[j];
            dp_im[j] = t_re * w_im[j] + t_im * w_re[j];
        }

        // ---- back substitution --------------------------------------
        double x_re = dp_re[n - 1];
        double x_im = dp_im[n - 1];
        u[base + n - 1] = x_re;
        v[base + n - 1] = x_im;
        for (int j = n - 2; j >= 0; --j) {
            // x_j = dp_j - cp_j * x_{j+1}
            const double pr = cp_re[j] * x_re - cp_im[j] * x_im;
            const double pi = cp_re[j] * x_im + cp_im[j] * x_re;
            x_re = dp_re[j] - pr;
            x_im = dp_im[j] - pi;
            u[base + j] = x_re;
            v[base + j] = x_im;
        }
    }
}

// ---------------------------------------------------------------------
// Phase 3/5 and 4: Cayley solves along y and z
// ---------------------------------------------------------------------
//
// Along y and z a line is strided (Width, and Width*Height). Solving one
// such line at a time would touch one double per cache line. Instead each
// unit of work carries kLaneWidth *adjacent x values* through the
// recurrence together: the inner loop over lanes is unit-stride and
// dependency-free, so it vectorises, and every cache line loaded is fully
// consumed.

void PhonoEngine::SweepY(int worker, int begin, int end) noexcept {
    if (!ready_) {
        return;
    }
    const int blocks_per_plane = (width_ + kLaneWidth - 1) / kLaneWidth;
    const int units = depth_ * blocks_per_plane;
    if (begin < 0) begin = 0;
    if (end > units) end = units;

    const int n = height_;
    if (n <= 0) {
        return;
    }
    const std::size_t stride = static_cast<std::size_t>(width_);

    double* __restrict u = psi_real_.data();
    double* __restrict v = psi_imag_.data();
    const double r = fy_.r;
    const double* __restrict cp_re = fy_.cp_re.data();
    const double* __restrict cp_im = fy_.cp_im.data();
    const double* __restrict w_re = fy_.w_re.data();
    const double* __restrict w_im = fy_.w_im.data();

    double* __restrict scratch = WorkerScratch(worker);
    double* __restrict dp_re = scratch;
    double* __restrict dp_im = scratch + static_cast<std::size_t>(n) * kLaneWidth;

    double row_re[kLaneWidth];
    double row_im[kLaneWidth];

    for (int unit = begin; unit < end; ++unit) {
        const int z = unit / blocks_per_plane;
        const int bx = unit - z * blocks_per_plane;
        const int x0 = bx * kLaneWidth;
        int lanes = width_ - x0;
        if (lanes > kLaneWidth) lanes = kLaneWidth;
        if (lanes <= 0) continue;

        const std::size_t base =
            static_cast<std::size_t>(z) * height_ * width_ + x0;

        // ---- j = 0: no predecessor row --------------------------------
        // A one-cell axis has no successor row either: the walls sit on
        // both sides of the single unknown, so the <false,false> form is
        // the one that stays in bounds.
        if (n > 1) {
            RhsRow<false, true>(u, v, base, stride, lanes, r, row_re, row_im);
        } else {
            RhsRow<false, false>(u, v, base, stride, lanes, r, row_re, row_im);
        }
        for (int l = 0; l < lanes; ++l) {
            dp_re[l] = row_re[l] * w_re[0] - row_im[l] * w_im[0];
            dp_im[l] = row_re[l] * w_im[0] + row_im[l] * w_re[0];
        }

        // ---- interior rows --------------------------------------------
        for (int j = 1; j < n - 1; ++j) {
            const std::size_t idx = base + static_cast<std::size_t>(j) * stride;
            RhsRow<true, true>(u, v, idx, stride, lanes, r, row_re, row_im);
            const double wr = w_re[j];
            const double wi = w_im[j];
            const std::size_t off = static_cast<std::size_t>(j) * kLaneWidth;
            const std::size_t prev = off - kLaneWidth;
            for (int l = 0; l < lanes; ++l) {
                const double t_re = row_re[l] - r * dp_im[prev + l];
                const double t_im = row_im[l] + r * dp_re[prev + l];
                dp_re[off + l] = t_re * wr - t_im * wi;
                dp_im[off + l] = t_re * wi + t_im * wr;
            }
        }

        // ---- j = n-1: no successor row ---------------------------------
        if (n > 1) {
            const int j = n - 1;
            const std::size_t idx = base + static_cast<std::size_t>(j) * stride;
            RhsRow<true, false>(u, v, idx, stride, lanes, r, row_re, row_im);
            const double wr = w_re[j];
            const double wi = w_im[j];
            const std::size_t off = static_cast<std::size_t>(j) * kLaneWidth;
            const std::size_t prev = off - kLaneWidth;
            for (int l = 0; l < lanes; ++l) {
                const double t_re = row_re[l] - r * dp_im[prev + l];
                const double t_im = row_im[l] + r * dp_re[prev + l];
                dp_re[off + l] = t_re * wr - t_im * wi;
                dp_im[off + l] = t_re * wi + t_im * wr;
            }
        }

        // ---- back substitution -----------------------------------------
        {
            const std::size_t off = static_cast<std::size_t>(n - 1) * kLaneWidth;
            const std::size_t idx =
                base + static_cast<std::size_t>(n - 1) * stride;
            for (int l = 0; l < lanes; ++l) {
                u[idx + l] = dp_re[off + l];
                v[idx + l] = dp_im[off + l];
            }
        }
        for (int j = n - 2; j >= 0; --j) {
            const std::size_t off = static_cast<std::size_t>(j) * kLaneWidth;
            const std::size_t idx = base + static_cast<std::size_t>(j) * stride;
            const std::size_t nxt = idx + stride;
            const double cr = cp_re[j];
            const double ci = cp_im[j];
            for (int l = 0; l < lanes; ++l) {
                const double xr = u[nxt + l];
                const double xi = v[nxt + l];
                u[idx + l] = dp_re[off + l] - (cr * xr - ci * xi);
                v[idx + l] = dp_im[off + l] - (cr * xi + ci * xr);
            }
        }
    }
}

void PhonoEngine::SweepZ(int worker, int begin, int end) noexcept {
    if (!ready_) {
        return;
    }
    const int blocks_per_plane = (width_ + kLaneWidth - 1) / kLaneWidth;
    const int units = height_ * blocks_per_plane;
    if (begin < 0) begin = 0;
    if (end > units) end = units;

    const int n = depth_;
    if (n <= 0) {
        return;
    }
    const std::size_t stride =
        static_cast<std::size_t>(width_) * static_cast<std::size_t>(height_);

    double* __restrict u = psi_real_.data();
    double* __restrict v = psi_imag_.data();
    const double r = fz_.r;
    const double* __restrict cp_re = fz_.cp_re.data();
    const double* __restrict cp_im = fz_.cp_im.data();
    const double* __restrict w_re = fz_.w_re.data();
    const double* __restrict w_im = fz_.w_im.data();

    double* __restrict scratch = WorkerScratch(worker);
    double* __restrict dp_re = scratch;
    double* __restrict dp_im = scratch + static_cast<std::size_t>(n) * kLaneWidth;

    double row_re[kLaneWidth];
    double row_im[kLaneWidth];

    for (int unit = begin; unit < end; ++unit) {
        const int y = unit / blocks_per_plane;
        const int bx = unit - y * blocks_per_plane;
        const int x0 = bx * kLaneWidth;
        int lanes = width_ - x0;
        if (lanes > kLaneWidth) lanes = kLaneWidth;
        if (lanes <= 0) continue;

        const std::size_t base =
            static_cast<std::size_t>(y) * width_ + x0;

        // A one-cell axis has no successor row either: the walls sit on
        // both sides of the single unknown, so the <false,false> form is
        // the one that stays in bounds.
        if (n > 1) {
            RhsRow<false, true>(u, v, base, stride, lanes, r, row_re, row_im);
        } else {
            RhsRow<false, false>(u, v, base, stride, lanes, r, row_re, row_im);
        }
        for (int l = 0; l < lanes; ++l) {
            dp_re[l] = row_re[l] * w_re[0] - row_im[l] * w_im[0];
            dp_im[l] = row_re[l] * w_im[0] + row_im[l] * w_re[0];
        }

        for (int j = 1; j < n - 1; ++j) {
            const std::size_t idx = base + static_cast<std::size_t>(j) * stride;
            RhsRow<true, true>(u, v, idx, stride, lanes, r, row_re, row_im);
            const double wr = w_re[j];
            const double wi = w_im[j];
            const std::size_t off = static_cast<std::size_t>(j) * kLaneWidth;
            const std::size_t prev = off - kLaneWidth;
            for (int l = 0; l < lanes; ++l) {
                const double t_re = row_re[l] - r * dp_im[prev + l];
                const double t_im = row_im[l] + r * dp_re[prev + l];
                dp_re[off + l] = t_re * wr - t_im * wi;
                dp_im[off + l] = t_re * wi + t_im * wr;
            }
        }

        if (n > 1) {
            const int j = n - 1;
            const std::size_t idx = base + static_cast<std::size_t>(j) * stride;
            RhsRow<true, false>(u, v, idx, stride, lanes, r, row_re, row_im);
            const double wr = w_re[j];
            const double wi = w_im[j];
            const std::size_t off = static_cast<std::size_t>(j) * kLaneWidth;
            const std::size_t prev = off - kLaneWidth;
            for (int l = 0; l < lanes; ++l) {
                const double t_re = row_re[l] - r * dp_im[prev + l];
                const double t_im = row_im[l] + r * dp_re[prev + l];
                dp_re[off + l] = t_re * wr - t_im * wi;
                dp_im[off + l] = t_re * wi + t_im * wr;
            }
        }

        {
            const std::size_t off = static_cast<std::size_t>(n - 1) * kLaneWidth;
            const std::size_t idx =
                base + static_cast<std::size_t>(n - 1) * stride;
            for (int l = 0; l < lanes; ++l) {
                u[idx + l] = dp_re[off + l];
                v[idx + l] = dp_im[off + l];
            }
        }
        for (int j = n - 2; j >= 0; --j) {
            const std::size_t off = static_cast<std::size_t>(j) * kLaneWidth;
            const std::size_t idx = base + static_cast<std::size_t>(j) * stride;
            const std::size_t nxt = idx + stride;
            const double cr = cp_re[j];
            const double ci = cp_im[j];
            for (int l = 0; l < lanes; ++l) {
                const double xr = u[nxt + l];
                const double xi = v[nxt + l];
                u[idx + l] = dp_re[off + l] - (cr * xr - ci * xi);
                v[idx + l] = dp_im[off + l] - (cr * xi + ci * xr);
            }
        }
    }
}

