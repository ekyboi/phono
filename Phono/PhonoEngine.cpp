// PhonoEngine.cpp -- Crank-Nicolson propagator for the 3D TDSE.
//
// =====================================================================
// THE CALCULUS, IN FULL
// =====================================================================
//
// -- 1. The equation ---------------------------------------------------
//
// The time-dependent Schrodinger equation is a first-order-in-time,
// second-order-in-space complex PDE:
//
//     i*hbar dPsi/dt = H Psi,   H = -(hbar^2/2m) (d2/dx2+d2/dy2+d2/dz2) + V
//
// H is Hermitian, so the exact propagator U(dt) = exp(-i H dt/hbar) is
// unitary: <Psi|Psi> is a conserved quantity. Any scheme worth using has
// to inherit that property, because |Psi|^2 is a probability density and
// a scheme that leaks norm is reporting that the particle is ceasing to
// exist.
//
// -- 2. Why Crank-Nicolson, and not forward Euler ----------------------
//
// Forward (explicit) Euler is Psi^{n+1} = (1 - i H dt/hbar) Psi^n. Its
// amplification factor for an eigenvalue E of H is |1 - iEdt/hbar| =
// sqrt(1 + (E dt/hbar)^2) > 1. Every mode grows. It is unconditionally
// *unstable* for this equation -- no dt saves it.
//
// Crank-Nicolson averages the spatial operator across the step, i.e. it
// applies the trapezoid rule to dPsi/dt = -(i/hbar) H Psi:
//
//     Psi^{n+1} = Psi^n - (i dt / 2hbar) H (Psi^n + Psi^{n+1})
//
// Group the unknowns on the left:
//
//     (I + i dt/(2hbar) H) Psi^{n+1} = (I - i dt/(2hbar) H) Psi^n   (*)
//
// This is the Cayley transform of H. Its amplification factor is
//
//     (1 - iEdt/2hbar) / (1 + iEdt/2hbar)
//
// a ratio of a complex number to its own conjugate, so its modulus is
// exactly 1 for every eigenvalue E and every dt. The scheme is
// unconditionally stable AND exactly unitary -- norm is conserved to
// rounding error, not merely to truncation order. Expanding both sides
// shows it matches exp(-iHdt/hbar) through the dt^2 term, so it is
// second-order accurate in time.
//
// The price is the word "implicit": (*) is a linear *system*. In 3D the
// matrix I + i dt/(2hbar) H is N x N with N = W*H*D and a seven-point
// stencil. Solving that directly, per step, is what the rest of this
// file is about avoiding.
//
// -- 3. Operator splitting: how a 3D implicit solve becomes 1D ---------
//
// Split the Hamiltonian along the axes:
//
//     H = V + Tx + Ty + Tz,   Td = -(hbar^2/2m) d2/d(axis)^2
//
// Each piece is separately Hermitian, so the Cayley transform of each is
// separately unitary. Compose them symmetrically (Strang splitting):
//
//     U(dt) ~= V(dt/2) X(dt/2) Y(dt/2) Z(dt) Y(dt/2) X(dt/2) V(dt/2)
//
// A palindromic composition of second-order-accurate factors is itself
// second-order accurate: the first-order commutator error [A,B]dt^2/2
// generated by the forward half cancels against the one generated by the
// reverse half. (Applying X, Y, Z once each in a fixed order would leave
// that term uncancelled and drop the scheme to first order.) Because
// every factor is unitary, so is the product -- the splitting costs
// accuracy, never stability and never norm.
//
// The payoff: Td involves only one axis, so its Cayley system decouples
// into independent tridiagonal systems, one per grid line along that
// axis. Each is solved in O(n) by the Thomas algorithm, and the lines
// are mutually independent, which is exactly the shape that shards
// across cores.
//
// -- 4. The 1D system, discretised -------------------------------------
//
// Central second difference on a uniform grid of spacing h:
//
//     d2Psi/dx2 |_j = (Psi_{j-1} - 2 Psi_j + Psi_{j+1}) / h^2 + O(h^2)
//
// so with alpha = -hbar^2/(2 m h^2), Td Psi_j = alpha(Psi_{j-1} - 2Psi_j
// + Psi_{j+1}). Substituting into (*) with step tau and writing
// lambda = i tau alpha / (2 hbar) = -i * tau*hbar/(4 m h^2), define
//
//     r = tau * hbar / (4 * m * h^2)     so lambda = -i r
//
// The row j of the system is then
//
//     -i r Psi*_{j-1} + (1 + 2 i r) Psi*_j - i r Psi*_{j+1}
//         = Psi_j + i r (Psi_{j-1} - 2 Psi_j + Psi_{j+1})
//
// A constant-coefficient complex tridiagonal system: sub- and
// super-diagonal a = c = -i r, diagonal b = 1 + 2 i r, right-hand side
// the explicit half of the same stencil. Dirichlet walls mean the ghost
// values at j = -1 and j = n vanish, so all n points are unknowns.
//
// Splitting into real (u) and imaginary (v) parts, with
// Lu_j = u_{j-1} - 2u_j + u_{j+1}:
//
//     d_re_j = u_j - r * Lv_j
//     d_im_j = v_j + r * Lu_j
//
// -- 5. Thomas, with the factorisation hoisted out of the loop ---------
//
// Forward elimination:
//     w_0 = 1/b,             cp_0 = c * w_0,        dp_0 = d_0 * w_0
//     w_j = 1/(b - a cp_{j-1}), cp_j = c * w_j,
//     dp_j = (d_j - a dp_{j-1}) * w_j
// Back substitution:
//     x_{n-1} = dp_{n-1},    x_j = dp_j - cp_j x_{j+1}
//
// a, b and c do not depend on j or on which line is being solved, so
// {w_j, cp_j} depend only on the axis length and on r. They are computed
// once per PrepareStep() and reused across all Height*Depth lines --
// turning the per-line cost into two multiply-add passes.
//
// -- 6. The diagonal factor --------------------------------------------
//
// V is diagonal, so its exact propagator is a pointwise phase rotation
// exp(-i V tau / hbar) -- no linear solve, no Cayley approximation
// needed, and exactly unitary. For a static V and fixed dt the phase is
// constant in time, so cos and sin are tabulated in PrepareStep() and
// the half-step degenerates to a 2x2 rotation per grid point.
//
// =====================================================================

