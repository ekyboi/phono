void PhonoEngine::StepTime(double dt) noexcept {
    if (!ready_) {
        return;
    }
    PrepareStep(dt);

    const int n = size_;
    const int xl = XLineCount();
    const int yb = YBlockCount();
    const int zb = ZBlockCount();

    // The palindrome from section 3. Reading it aloud is the algorithm:
    // half a kick, half a drift in x, half in y, a full drift in z, then
    // unwind the same sequence in reverse.
    ApplyPotentialHalfStep(0, n);
    SweepX(0, 0, xl);
    SweepY(0, 0, yb);
    SweepZ(0, 0, zb);
    SweepY(0, 0, yb);
    SweepX(0, 0, xl);
    ApplyPotentialHalfStep(0, n);
}

