PhonoEngine::PhonoEngine(int width, int height, int depth,
                         double dx, double dy, double dz,
                         double hbar, double mass,
                         int max_workers) noexcept
    : width_(width > 0 ? width : 0),
      height_(height > 0 ? height : 0),
      depth_(depth > 0 ? depth : 0),
      size_(0),
      max_workers_(max_workers > 0 ? max_workers : 1),
      dx_(dx),
      dy_(dy),
      dz_(dz),
      hbar_(hbar),
      mass_(mass) {
    // Computed rather than assigned in the member list so the clamped
    // extents above are the ones multiplied.
    size_ = width_ * height_ * depth_;
}

PhonoEngine::~PhonoEngine() {
    ::operator delete(scratch_, std::align_val_t(kCacheLineBytes));
    scratch_ = nullptr;
}

bool PhonoEngine::Initialize() noexcept {
    if (ready_) {
        return true;
    }
    if (size_ <= 0 || dx_ <= 0.0 || dy_ <= 0.0 || dz_ <= 0.0 ||
        hbar_ <= 0.0 || mass_ <= 0.0) {
        return false;
    }

    // std::vector reports exhaustion by throwing. An exception must not
    // cross the extern "C" bridge frame into the Go runtime, so it is
    // caught here and reported as a bool, mirroring the `new
    // (std::nothrow)` discipline the generated bridge uses for the object
    // itself.
    try {
        const std::size_t n = static_cast<std::size_t>(size_);
        psi_real_.assign(n, 0.0);
        psi_imag_.assign(n, 0.0);
        potential_.assign(n, 0.0);
        density_.assign(n, 0.0);
        phase_cos_.assign(n, 1.0);
        phase_sin_.assign(n, 0.0);

        fx_.cp_re.assign(static_cast<std::size_t>(width_), 0.0);
        fx_.cp_im.assign(static_cast<std::size_t>(width_), 0.0);
        fx_.w_re.assign(static_cast<std::size_t>(width_), 0.0);
        fx_.w_im.assign(static_cast<std::size_t>(width_), 0.0);

        fy_.cp_re.assign(static_cast<std::size_t>(height_), 0.0);
        fy_.cp_im.assign(static_cast<std::size_t>(height_), 0.0);
        fy_.w_re.assign(static_cast<std::size_t>(height_), 0.0);
        fy_.w_im.assign(static_cast<std::size_t>(height_), 0.0);

        fz_.cp_re.assign(static_cast<std::size_t>(depth_), 0.0);
        fz_.cp_im.assign(static_cast<std::size_t>(depth_), 0.0);
        fz_.w_re.assign(static_cast<std::size_t>(depth_), 0.0);
        fz_.w_im.assign(static_cast<std::size_t>(depth_), 0.0);
    } catch (...) {
        return false;
    }

    // Scratch holds the forward-elimination vector dp for one blocked
    // solve: the longest axis, times the lane width, times two for the
    // real and imaginary parts. Each worker's slab starts on its own
    // cache line, so two cores sweeping different lines never contend for
    // one line's ownership.
    int longest = width_;
    if (height_ > longest) longest = height_;
    if (depth_ > longest) longest = depth_;

    const std::size_t slab_doubles =
        static_cast<std::size_t>(longest) * kLaneWidth * 2u;
    const std::size_t slab_bytes = PadToCacheLine(slab_doubles * sizeof(double));
    scratch_stride_ = slab_bytes / sizeof(double);

    const std::size_t total = scratch_stride_ *
                              static_cast<std::size_t>(max_workers_) *
                              sizeof(double);
    scratch_ = static_cast<double*>(::operator new(
        total, std::align_val_t(kCacheLineBytes), std::nothrow));
    if (scratch_ == nullptr) {
        return false;
    }
    std::memset(scratch_, 0, total);

    ready_ = true;
    return true;
}

bool PhonoEngine::Ready() const noexcept { return ready_; }

